package com.example.engine

import com.example.data.model.ChatMessage
import com.example.data.model.MessageSender
import com.example.data.model.ProviderConfig
import com.example.data.remote.LLMStreamService
import com.example.data.repository.ProviderRepository
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flow
import kotlinx.coroutines.flow.toList

class LLMProviderManager {

    private var providerRepository: ProviderRepository? = null
    private var activeProviderSupplier: (suspend () -> ProviderConfig)? = null
    private var providerRouter: ProviderRouter? = null

    constructor(providerRepository: ProviderRepository) {
        this.providerRepository = providerRepository
        this.providerRouter = ProviderRouter(providerRepository)
    }

    constructor(activeProviderSupplier: suspend () -> ProviderConfig) {
        this.activeProviderSupplier = activeProviderSupplier
    }

    fun streamResponse(
        messages: List<ChatMessage>,
        systemInstruction: String,
        overrideModelId: String? = null,
        isHighThinking: Boolean = false
    ): Flow<String> = flow {
        val router = providerRouter
        if (router != null) {
            val lastUserMessage = messages.lastOrNull { it.sender == MessageSender.USER }?.content ?: ""
            val modelToUse = overrideModelId ?: ""

            when (val routing = router.routeRequest(lastUserMessage, messages, modelToUse)) {
                is RoutingResult.Success -> {
                    if (routing.isImageGeneration && !routing.directImageResponse.isNullOrBlank()) {
                        emit(routing.directImageResponse)
                    } else {
                        LLMStreamService.generateStream(
                            provider = routing.provider,
                            modelId = routing.targetModelId,
                            messages = messages,
                            systemInstruction = systemInstruction,
                            isHighThinking = isHighThinking
                        ).collect { chunk ->
                            emit(chunk)
                        }
                    }
                }

                is RoutingResult.ProviderDisabled -> {
                    emit("Error: ${routing.userActionRequired}")
                }

                is RoutingResult.Error -> {
                    emit("Routing Error: ${routing.message}")
                }
            }
        } else {
            val provider = activeProviderSupplier?.invoke() ?: return@flow
            val model = overrideModelId?.ifBlank { null } ?: provider.selectedModel
            LLMStreamService.generateStream(
                provider = provider,
                modelId = model,
                messages = messages,
                systemInstruction = systemInstruction,
                isHighThinking = isHighThinking
            ).collect { chunk ->
                emit(chunk)
            }
        }
    }

    suspend fun singleTurnQuery(
        systemInstruction: String,
        prompt: String,
        overrideModelId: String? = null
    ): String {
        val messages = listOf(ChatMessage(threadId = "agent", sender = MessageSender.USER, content = prompt))
        val chunks = mutableListOf<String>()
        streamResponse(
            messages = messages,
            systemInstruction = systemInstruction,
            overrideModelId = overrideModelId
        ).toList(chunks)

        val fullText = chunks.joinToString("")
        return if (fullText.isNotBlank()) fullText else "No output generated by model ${overrideModelId ?: "default"}."
    }
}
