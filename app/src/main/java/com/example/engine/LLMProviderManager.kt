package com.example.engine

import com.example.data.model.ChatMessage
import com.example.data.model.MessageSender
import com.example.data.model.ProviderConfig
import com.example.data.remote.LLMStreamService
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.toList

class LLMProviderManager(private val activeProviderSupplier: suspend () -> ProviderConfig) {

    fun streamResponse(
        messages: List<ChatMessage>,
        systemInstruction: String,
        overrideModelId: String? = null,
        isHighThinking: Boolean = false
    ): Flow<String> = kotlinx.coroutines.flow.flow {
        val provider = activeProviderSupplier()
        val model = overrideModelId ?: provider.selectedModel
        LLMStreamService.generateStream(
            provider = provider,
            modelId = model,
            messages = messages,
            systemInstruction = systemInstruction,
            isHighThinking = isHighThinking
        ).collect { chunk ->
            emit(chunk)
        }
    }

    suspend fun singleTurnQuery(
        systemInstruction: String,
        prompt: String,
        overrideModelId: String? = null
    ): String {
        val provider = activeProviderSupplier()
        val model = overrideModelId ?: provider.selectedModel
        val messages = listOf(ChatMessage(threadId = "agent", sender = MessageSender.USER, content = prompt))

        val chunks = mutableListOf<String>()
        LLMStreamService.generateStream(
            provider = provider,
            modelId = model,
            messages = messages,
            systemInstruction = systemInstruction
        ).toList(chunks)

        val fullText = chunks.joinToString("")
        return if (fullText.isNotBlank()) fullText else "No output generated by model $model."
    }
}
